#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════
   generate-write-perms — مولدِ جدولِ مجوزِ نوشتارِ سرور (R99)
   ───────────────────────────────────────────────────────────────────
   تک‌منبعِ مجوزها:
     ۱. ACTION_ROLES در src/js/30-authz.js — نقش‌هایِ مجازِ هر اکشن
     ۲. تحلیلِ استاتیکِ اکشن‌ها (19-actions-*.js) — مجموعه‌هایی که هر
        اکشن می‌نویسد (همان استخراجِ tools/check-authz.js)
     ۳. authz/model.json — fields + نقش‌هایِ هر عمل (ins/upd/del)؛
        منبعِ کوراکشن (GRANTS) برایِ مولد

   خروجی: authz/write-perms.json — جدولی که server/sync.js می‌خواند
   (نه جدولِ دستی). بخشِ `actions` همان نقشهٔ صریحِ «اکشن ← نقش‌ها +
   مجموعه‌هایِ قابلِ نوشتن» است که در فایلِ تولیدی قفل می‌شود.

   سازگاری (fail-closed): اگر نقشی در ACTION_ROLES، حقِ نوشتنِ
   مجموعهٔ اکشنش را در مدل نداشته باشد، مولد با exit 1 می‌میرد و
   فایل را نمی‌نویسد (همان معیارِ tools/check-authz.js — یک منبع).

   اجرا:   node tools/generate-write-perms.js          (تولید + نوشتن)
           node tools/generate-write-perms.js --check  (فقط مقایسهٔ
                 خروجیِ محاسبه‌شده با فایلِ موجود — برایِ build.js --check)
   ═══════════════════════════════════════════════════════════════════ */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const MODEL_PATH = path.join(ROOT, 'authz', 'model.json');
const OUT_PATH = path.join(ROOT, 'authz', 'write-perms.json');

const { extract, parseActionRoles } = require('./check-authz.js');

/* استثنایِ محدودشدهٔ سمتِ سرور (آینهٔ sync.js): teacher روی users فقط
   با کلیدهایِ IEP/DROP — بند ۲.۲. */
const SCOPED = { teacher: { users: true } };
/* ترتیبِ پایدارِ نقش‌ها برایِ خروجیِ قطعی */
const ROLE_ORDER = ['manager', 'teacher', 'parent', 'student', 'driver', 'counselor', 'edu_office'];

function generate(){
  const model = JSON.parse(fs.readFileSync(MODEL_PATH, 'utf8'));
  const collections = model.collections || {};

  /* ۱) ops + fields از مدل (منبعِ کوراکشن — ترتیبِ کلیدها عینِ مدل) */
  const ops = {};
  const fields = {};
  for (const c of Object.keys(collections)){
    const def = collections[c] || {};
    ops[c] = {
      ins: (def.ins || []).slice(),
      upd: (def.upd || []).slice(),
      del: (def.del || []).slice()
    };
    fields[c] = (def.fields || []).slice();
  }

  /* ۲) perms — superadmin = '*' (اصلِ ساختاری)؛ هر نقش = مجموعه‌هایی که
     در هر عمل در آن‌ها ظاهر می‌شود (دقیقاً همان مشتقِ پیشینِ sync.js) */
  const perms = { superadmin: ['*'] };
  for (const c of Object.keys(ops)){
    const rs = new Set();
    for (const t of ['ins', 'upd', 'del']){
      for (const r of ops[c][t]) if (r !== 'superadmin') rs.add(r);
    }
    for (const r of rs) (perms[r] = perms[r] || []).push(c);
  }
  const ordered = { superadmin: ['*'] };
  for (const r of ROLE_ORDER) if (perms[r]) ordered[r] = perms[r].slice().sort();
  for (const r of Object.keys(perms)) if (!ordered[r]) ordered[r] = perms[r].slice().sort();

  /* ۳) سازگاری: ACTION_ROLES (کلاینت) ↔ perms — هر اکشنِ نویسنده،
     نقش‌هایش باید حقِ نوشتنِ همهٔ مجموعه‌هایش را داشته باشند. */
  const ex = extract();
  const actionRoles = parseActionRoles();
  const violations = [];
  for (const [name, a] of Object.entries(ex.actions)){
    if (!a.colls.length) continue;
    const roles = actionRoles[name];
    if (!roles) continue; /* اکشنِ بی‌برچسب — fail-closedِ سرور نگهبان است */
    for (const role of roles){
      if (role === 'superadmin') continue;
      for (const coll of a.colls){
        if (SCOPED[role] && SCOPED[role][coll]) continue;
        const list = ordered[role];
        if (!list || list.indexOf(coll) === -1){
          violations.push(`${name} — ${role} → ${coll}`);
        }
      }
    }
  }
  if (violations.length){
    console.error(`❌ generate-write-perms: ${violations.length} ناهماهنگی بینِ ACTION_ROLES و مدلِ مجوزها:`);
    violations.forEach(v => console.error('   ' + v));
    console.error('   authz/model.json (کوراکشن) یا ACTION_ROLES را همگام کنید؛ فایل نوشته نشد.');
    process.exit(1);
  }

  /* ۴) نقشهٔ صریحِ «اکشن ← نقش‌ها + مجموعه‌هایِ قابلِ نوشتن» (تولیدشده،
     نه دست‌نویس) — خروجیِ تحلیلِ استاتیک در فایلِ قفل‌شده */
  const actions = {};
  for (const name of Object.keys(ex.actions).sort()){
    const a = ex.actions[name];
    if (!a.colls.length) continue;
    actions[name] = { roles: actionRoles[name] || null, collections: a.colls };
  }

  return {
    source: 'AUTO-GENERATED by tools/generate-write-perms.js — دستی ویرایش نشود',
    generatedFrom: [
      'src/js/30-authz.js (ACTION_ROLES)',
      'static analysis of actions (19-actions-*.js + helper fns)',
      'authz/model.json (fields + per-op roles)'
    ],
    perms: ordered,
    ops,
    fields,
    actions
  };
}

function main(){
  const check = process.argv.includes('--check');
  const out = JSON.stringify(generate(), null, 2) + '\n';
  if (check){
    if (!fs.existsSync(OUT_PATH)){
      console.error(`❌ generate-write-perms --check: ${path.relative(ROOT, OUT_PATH)} وجود ندارد — node tools/generate-write-perms.js را اجرا کنید.`);
      process.exit(1);
    }
    const cur = fs.readFileSync(OUT_PATH, 'utf8');
    if (cur !== out){
      console.error(`❌ generate-write-perms --check: ${path.relative(ROOT, OUT_PATH)} با خروجیِ مولد یکسان نیست (کهنه است).`);
      console.error('   node tools/generate-write-perms.js را اجرا کنید و نتیجه را commit کنید.');
      process.exit(1);
    }
    console.log('✅ generate-write-perms: authz/write-perms.json با منبعِ یکسان است (ACTION_ROLES + analysis + model).');
    return;
  }
  fs.writeFileSync(OUT_PATH, out);
  const obj = JSON.parse(out);
  console.log(`✅ generate-write-perms: ${path.relative(ROOT, OUT_PATH)} نوشته شد — ${Object.keys(obj.ops).length} مجموعه، ${Object.keys(obj.actions).length} اکشنِ نویسنده، نقش‌ها: ${Object.keys(obj.perms).join(', ')}.`);
}

main();
