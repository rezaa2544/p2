/* ── ۱) پارس مهاجرت‌ها ───────────────────────────────────────────── */
function parseTables(sql) {
  const tables = {};
  const re = /CREATE TABLE IF NOT EXISTS ([a-z_]+) \(([\s\S]*?)\n\);/g;
  let m;
  while ((m = re.exec(sql)) !== null) {
    const name = m[1];
    const body = m[2];
    const cols = [], cons = [];
    for (const raw of body.split('\n')) {
      const line = raw.trim().replace(/,\s*$/, '');
      if (!line) continue;
      if (line.startsWith('CONSTRAINT ')) {
        const fk = line.match(/^CONSTRAINT (\w+) FOREIGN KEY \((\w+)\) REFERENCES (\w+)\((\w+)\)(.*)$/);
        const ck = line.match(/^CONSTRAINT (\w+) CHECK \(([\s\S]*)\)$/);
        const uq = line.match(/^CONSTRAINT (\w+) UNIQUE \(([\s\S]*)\)$/);
        if (fk) cons.push({ kind: 'FK', name: fk[1], col: fk[2], ref: `${fk[3]}(${fk[4]})`, extra: fk[5].trim() });
        else if (ck) cons.push({ kind: 'CHECK', name: ck[1], expr: ck[2] });
        else if (uq) cons.push({ kind: 'UNIQUE', name: uq[1], cols: uq[2] });
        continue;
      }
      const cm = line.match(/^"?(\w+)"?\s+([A-Z]+(?:\(\d+\))?)\s*(.*)$/);
      if (!cm) continue;
      const rest = cm[3] || '';
      cols.push({
        name: cm[1], type: cm[2],
        pk: /PRIMARY KEY/.test(rest),
        nn: /NOT NULL/.test(rest),
        def: (rest.match(/DEFAULT (NOW\(\)|'[^']*'|\d+)/) || [])[1] || null,
        identity: /GENERATED BY DEFAULT AS IDENTITY/.test(rest),
      });
    }
    tables[name] = { cols, cons };
  }
  return tables;
}
function parseIndexes(sql) {
  const idx = [];
  const re = /CREATE INDEX IF NOT EXISTS (\w+) ON (\w+)(?: USING (\w+))? \(([^)]*)\)/g;
  let m;
  while ((m = re.exec(sql)) !== null) idx.push({ name: m[1], table: m[2], method: m[3] || 'BTREE', cols: m[4] });
  return idx;
}
