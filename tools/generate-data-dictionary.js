{ // ۰۰۲ ایندکس‌های تکراری با انتهای ۰۰۱ دارد — با نام یکتا ادغام می‌شود
  const seen = new Set(indexes.map((i) => i.name));
  for (const i of parseIndexes(rd('migrations/002_indexes.sql'))) if (!seen.has(i.name)) { indexes.push(i); seen.add(i.name); }
}
