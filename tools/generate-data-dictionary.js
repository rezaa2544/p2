function sampleValue(t, col) {
  const n = col.name;
  if (SAMPLES[t] && n in SAMPLES[t]) return SAMPLES[t][n];
  if (n === 'id') return 1;
  if (n.endsWith('_at') || col.type === 'TIMESTAMPTZ') return '2026-09-10T07:30:00Z';
  if (col.type === 'JSONB') return {};
  if (n === 'school_id') return 1;
  if (n.endsWith('_id')) return 2;
  if (n === 'date') return '1405-07-01';
  if (col.type.startsWith('VARCHAR') || col.type === 'TEXT') return '…';
  if (col.type === 'INTEGER' || col.type === 'BIGINT') return 0;
  return null;
}

