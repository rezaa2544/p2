/* ═══════════════════════════════════════════════════════════════════
   tests/ids-cross-collection-live.js — A-AUTHZ-DUR-01 regression (live PG)
   ───────────────────────────────────────────────────────────────────
   Defect (pre-fix): server/ids.js remapped EVERY collection outside
   {attendance, classes, grades, users} to the 'users' namespace, so e.g.
   parent_links/messages drew ids from users_id_seq. With GENERATED BY
   DEFAULT AS IDENTITY and seeded/restored explicit ids (sequence lagging
   behind MAX(id)), the issued id collided with an existing row and the
   persistence upsert (ON CONFLICT (id) DO UPDATE) silently OVERWROTE an
   unrelated record while responding ok:true (reproduced live at 5d4a48f7).
   Fix: per-table owning sequence + forward-only advisory-locked alignment
   to MAX(id) on first use per process (server/ids.js).
   Requires: DATABASE_URL on a MIGRATED schema (migrations/*.sql applied).
   ═══════════════════════════════════════════════════════════════════ */
'use strict';
const assert = require('assert');
const { Pool } = require('pg');
const { createIds } = require('../server/ids');

const url = process.env.DATABASE_URL;
if (!url) { console.error('DATABASE_URL required (migrated DB)'); process.exit(1); }
const pool = new Pool({ connectionString: url });
const db = {
  isPostgres: () => true,
  query: (text, params) => pool.query(text, params)
};

const HI = 999900; /* explicit-id band far from normal data */
let checks = 0;
function check(name, cond, detail) {
  checks++;
  if (!cond) { console.error('IDS LIVE REGRESSION FAILED: ' + name + (detail ? ' :: ' + detail : '')); process.exit(1); }
  console.log('  PASS ' + name);
}

(async () => {
  console.log('\n=== A-AUTHZ-DUR-01 — live id-namespace regression ===');
  /* clean + seed the lag scenario: explicit high ids, sequences forced low */
  await pool.query('DELETE FROM parent_links WHERE id BETWEEN $1 AND $2', [HI, HI + 99]);
  await pool.query('DELETE FROM messages WHERE id BETWEEN $1 AND $2', [HI, HI + 99]);
  await pool.query('DELETE FROM users WHERE id BETWEEN $1 AND $2', [HI, HI + 99]);
  await pool.query('INSERT INTO parent_links (id, parent_id, student_id, relation) VALUES ($1,$2,$3,$4),($5,$6,$7,$8)',
    [HI + 1, HI + 1, HI + 2, 'پدر', HI + 2, HI + 3, HI + 4, 'مادر']);
  await pool.query('INSERT INTO users (id, role, full_name, active) VALUES ($1,$2,$3,true)', [HI + 5, 'student', 'id-test']);

  const plSeq = (await pool.query("SELECT pg_get_serial_sequence('parent_links','id') AS seq")).rows[0].seq;
  const usSeq = (await pool.query("SELECT pg_get_serial_sequence('users','id') AS seq")).rows[0].seq;
  const plSeqBefore = Number((await pool.query('SELECT last_value FROM ' + plSeq)).rows[0].last_value);
  const usSeqBefore = Number((await pool.query('SELECT last_value FROM ' + usSeq)).rows[0].last_value);
  await pool.query('SELECT setval($1, 1, true)', [plSeq]); /* force lag */

  const ids = createIds({ db, cache: null });

  /* 1 — parent_links id must clear the explicit-id band (alignment works) */
  const plId = await ids.nextId('parent_links', []);
  check('parent_links id aligned beyond MAX(id) (no collision band)', plId > HI + 2, 'got=' + plId);

  /* 2 — the users sequence must NOT have been consumed by parent_links */
  const usSeqAfter = Number((await pool.query('SELECT last_value FROM ' + usSeq)).rows[0].last_value);
  check('users sequence untouched by parent_links allocation', usSeqAfter === usSeqBefore, usSeqBefore + '→' + usSeqAfter);

  /* 3 — the allocated id actually inserts (no silent upsert over an existing row) */
  const cntBefore = Number((await pool.query('SELECT count(*)::int n FROM parent_links')).rows[0].n);
  await pool.query('INSERT INTO parent_links (id, parent_id, student_id, relation) VALUES ($1,$2,$3,$4)', [plId, HI + 5, HI + 6, 'قیم']);
  const cntAfter = Number((await pool.query('SELECT count(*)::int n FROM parent_links')).rows[0].n);
  check('allocated id inserts as a NEW row (count +1, no overwrite)', cntAfter === cntBefore + 1, cntBefore + '→' + cntAfter);

  /* 4 — an independent collection with its own lagged band aligns too */
  const msgSeq = (await pool.query("SELECT pg_get_serial_sequence('messages','id') AS seq")).rows[0].seq;
  await pool.query('INSERT INTO messages (id, body) VALUES ($1, $2)', [HI + 10, 'lag-seed']);
  await pool.query('SELECT setval($1, 1, true)', [msgSeq]); /* force lag */
  const msgId = await ids.nextId('messages', []);
  check('messages sequence aligns past its own band (no cross-table id)', msgId > HI + 10, 'got=' + msgId);
  const plId2 = msgId; /* keep later cleanup math intact */

  /* 5 — users namespace still works and aligns past its own band */
  const uId = await ids.nextId('users', []);
  check('users id aligned beyond its explicit band', uId > HI + 5, 'got=' + uId);

  /* 6 — 'students' is the users table alias (same identity space) */
  const sId = await ids.nextId('students', []);
  check('students alias draws from the users identity space', sId > HI + 5, 'got=' + sId);

  /* cleanup */
  await pool.query('DELETE FROM parent_links WHERE id BETWEEN $1 AND $2 OR parent_id BETWEEN $1 AND $2', [HI, HI + 99]);
  await pool.query('DELETE FROM messages WHERE id BETWEEN $1 AND $2', [HI, HI + 99]);
  await pool.query('DELETE FROM users WHERE id BETWEEN $1 AND $2', [HI, HI + 99]);
  await pool.query('SELECT setval($1, $2, true)', [plSeq, Math.max(plSeqBefore, plId2)]);

  console.log('\nIDS CROSS-COLLECTION LIVE REGRESSION: ' + checks + '/' + checks + ' PASS');
  await pool.end();
})().catch(err => {
  console.error('IDS LIVE REGRESSION FAILED:', err && err.stack || err);
  process.exit(1);
});
