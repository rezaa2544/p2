#!/usr/bin/env node
/* Mutation checks for Wave 2 DB Engineering.
   این فایل جهش‌های مشخصی را که قبلاً می‌توانستند بی‌صدا زنده بمانند،
   با وارسی استاتیک/رفتاری می‌کشد؛ بدون تغییر فایل‌های پروژه. */
'use strict';

const fs = require('fs');
const path = require('path');
const assert = require('assert');

const ROOT = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
let pass = 0;
function kill(name, fn){
  try{ fn(); pass++; console.log('  ✅ ' + name); }
  catch(e){ console.error('  ❌ جهش زنده ماند: ' + name); console.error(e && e.stack || e); process.exit(1); }
}

console.log('\n▸ Wave 2 — Database Engineering mutations');

kill('M1 حذف Identity از schema/migration کشته می‌شود', () => {
  assert.match(read('server/schema.sql'), /GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
  assert.match(read('migrations/001_initial.sql'), /GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
});

kill('M2 حذف rollback migration کشته می‌شود', () => {
  ['001_initial','002_indexes','003_constraints'].forEach(n => assert.ok(fs.existsSync(path.join(ROOT, 'migrations', n + '.down.sql'))));
});

kill('M3 حذف transaction از persistOpsBatch کشته می‌شود', () => {
  const t = read('server/db.js');
  assert.match(t, /return await transaction\(async \(client\)/);
});

kill('M4 تبدیل OCC SQL به update بدون version کشته می‌شود', () => {
  const t = read('server/db.js');
  assert.match(t, /WHERE id = \$\$?\{fields\.length \+ 1\} AND version = \$\$?\{fields\.length \+ 2\}/);
  assert.match(t, /e\.status = 409/);
});

kill('M5 برگشت max(id)+1 به مسیر PostgreSQL کشته می‌شود', () => {
  const ids = read('server/ids.js');
  const pgNextBody = ids.match(/const pgNext = async[\s\S]*?;\n\n  \/\* مکس\+۱ محافظت‌شده/)[0];
  assert.match(pgNextBody, /pg_get_serial_sequence/);
  assert.doesNotMatch(pgNextBody, /localMax\(list\) \+ 1/);
});

kill('M6 حذف transaction از سه مسیر حیاتی کشته می‌شود', () => {
  assert.match(read('server/routes/students.js'), /persistOpsBatch\(\[\{ c: 'users', t: 'ins'/);
  assert.match(read('server/routes/attendance.js'), /persistOpsBatch\(\[\{ c: 'attendance', t: 'ins'/);
  assert.match(read('server/routes/grades.js'), /persistOpsBatch\(\[\{ c: 'grades', t: 'ins'/);
});

console.log('\n────────────────────────────────────────────────────');
console.log('db-engineering-mutations: ' + pass + '/' + pass + ' جهش کشته شد ✅');
