#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════
   Wave 2 — Database Engineering tests
   پوشش: migrations، constraints، Identity IDs، transaction discipline و OCC SQL.
   بدون نیاز به PostgreSQL واقعی؛ با pool جعلی مسیرهای حساس را می‌سنجد.
   ═══════════════════════════════════════════════════════════════════ */
'use strict';

const fs = require('fs');
const path = require('path');
const assert = require('assert');
const db = require('../server/db');
const migrate = require('../tools/migrate-to-pg');

const ROOT = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
let pass = 0;
function ok(name, fn){
  try{ fn(); pass++; console.log('  ✅ ' + name); }
  catch(e){ console.error('  ❌ ' + name); console.error(e && e.stack || e); process.exit(1); }
}
async function okAsync(name, fn){
  try{ await fn(); pass++; console.log('  ✅ ' + name); }
  catch(e){ console.error('  ❌ ' + name); console.error(e && e.stack || e); process.exit(1); }
}

(async function main(){
  console.log('\n▸ Wave 2 — Database Engineering');

  const migDir = path.join(ROOT, 'migrations');
  ok('پوشه migrations وجود دارد', () => assert.ok(fs.statSync(migDir).isDirectory()));
  const forwards = fs.readdirSync(migDir).filter(f => /^\d{3}_[a-z0-9_]+\.sql$/.test(f)).sort();
  /* پیش‌تر این بررسی یک فهرستِ سخت‌کدِ چهارتایی بود و با افزودنِ هر مهاجرتِ تازه
     قرمز می‌شد (و روی main قرمز بود: ۷ فایل روی دیسک در برابر ۴ انتظار).
     حالا ساختار بررسی می‌شود، نه فهرست: شماره‌گذاریِ پیوسته و بی‌تکرار از ۰۰۱.
     این هم قوی‌تر است و هم با مهاجرتِ بعدی نمی‌شکند. */
  const migNums = forwards.map((f) => f.slice(0, 3));
  ok('migrationهای forward نسخه‌دار و مرتب هستند', () => {
    assert.ok(forwards.length >= 4, 'دستِ‌کم چهار مهاجرت انتظار می‌رود، یافت شد: ' + forwards.length);
    assert.deepStrictEqual(forwards, [...forwards].sort(), 'فایل‌ها باید بر اساس نام مرتب باشند');
  });
  ok('شماره‌گذاری پیوسته است و شمارهٔ تکراری وجود ندارد (سیاست MIGRATION_GUIDE §۱)', () => {
    const dupes = migNums.filter((n, i) => migNums.indexOf(n) !== i);
    assert.deepStrictEqual([...new Set(dupes)], [], 'شمارهٔ تکراری: ' + [...new Set(dupes)].join(','));
    const expected = migNums.map((_, i) => String(i + 1).padStart(3, '0'));
    assert.deepStrictEqual(migNums, expected,
      'شماره‌ها باید از ۰۰۱ پیوسته باشند؛ یافت شد: ' + migNums.join(','));
  });
  ok('برای هر migration فایل rollback وجود دارد', () => forwards.forEach(f => assert.ok(fs.existsSync(path.join(migDir, f.replace(/\.sql$/, '.down.sql'))))));
  ok('migration 004: ستون version روی ۹ جدولِ VERSION_TRACKED + دنباله outbox (idempotent)', () => {
    const m4 = read('migrations/004_wave1_version_seq.sql');
    for(const t of ['grades', 'attendance', 'discipline', 'schools', 'classes', 'subjects', 'users', 'enrollments', 'schedule'])
      assert.match(m4, new RegExp("table_name='" + t + "' AND column_name='version'"));
    assert.match(m4, /CREATE SEQUENCE IF NOT EXISTS payesh_outbox_id_seq/);
    assert.match(m4, /IF NOT EXISTS/);
    const d4 = read('migrations/004_wave1_version_seq.down.sql');
    assert.match(d4, /DROP SEQUENCE IF EXISTS payesh_outbox_id_seq/);
  });
  ok('migrationها transactional و immutable-style هستند', () => forwards.forEach(f => {
    const t = fs.readFileSync(path.join(migDir, f), 'utf8');
    assert.match(t, /BEGIN;/);
    assert.match(t, /COMMIT;/);
    assert.doesNotMatch(t, /\bDROP\s+TABLE\b/i);
  }));

  const schema = read('server/schema.sql');
  const initial = read('migrations/001_initial.sql');
  const constraints = read('migrations/003_constraints.sql');

  ok('schema و migration اولیه از Identity برای id استفاده می‌کنند', () => {
    assert.match(schema, /"id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
    assert.match(initial, /"id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
    assert.doesNotMatch(schema.split('\nBEGIN;')[0], /"id" INTEGER PRIMARY KEY/);
  });
  ok('قیود اصلی PK/FK/UNIQUE/CHECK/NOT NULL موجودند', () => {
    assert.match(initial, /PRIMARY KEY/);
    assert.match(initial, /FOREIGN KEY/);
    assert.match(initial, /UNIQUE/);
    assert.match(initial, /CHECK/);
    assert.match(initial, /NOT NULL/);
    assert.match(constraints, /chk_classes_capacity/);
    assert.match(constraints, /uq_enrollments_student_year/);
    assert.match(constraints, /uq_schedule_teacher_slot/);
    assert.match(constraints, /chk_users_status/);
    assert.match(constraints, /fk_grades_student/);
  });
  ok('مولد DDL سالم است و Identity تولید می‌کند', () => {
    const ddl = migrate.generateDDL();
    assert.match(ddl, /GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
    assert.match(ddl, /chk_users_status/);
  });
  ok('کد تولید migration دیگر تعریف تکراری valuesRows ندارد', () => {
    const t = read('tools/migrate-to-pg.js');
    assert.strictEqual((t.match(/const valuesRows = \[\];/g) || []).length, 1);
  });
  ok('هیچ مسیر PostgreSQL تولید id با max(id)+1 ندارد', () => {
    const ids = read('server/ids.js');
    assert.match(ids, /pg_get_serial_sequence/);
    assert.match(ids, /GENERATED BY DEFAULT AS IDENTITY|Identity|IDENTITY/i);
    const pgNextBody = ids.match(/const pgNext = async[\s\S]*?;\n\n  \/\* مکس\+۱ محافظت‌شده/)[0];
    assert.doesNotMatch(pgNextBody, /localMax\(list\) \+ 1/);
  });
  ok('سه مسیر حیاتی REST از persistOpsBatch/transaction استفاده می‌کنند', () => {
    assert.match(read('server/routes/students.js'), /persistOpsBatch\(\[\{ c: 'users', t: 'ins'/);
    assert.match(read('server/routes/attendance.js'), /persistOpsBatch\(\[\{ c: 'attendance', t: 'ins'/);
    assert.match(read('server/routes/grades.js'), /persistOpsBatch\(\[\{ c: 'grades', t: 'ins'/);
  });

  await okAsync('persistOpsBatch در PostgreSQL یک transaction واقعی می‌سازد', async () => {
    const calls = [];
    const client = { query: async (sql, params) => { calls.push([sql, params]); return { rows: [{ nextval: 1 }], rowCount: 1 }; }, release: () => calls.push(['RELEASE']) };
    db.__setPoolForTests({ connect: async () => client, end: async () => {} });
    await db.persistOpsBatch([{ c: 'grades', t: 'ins', data: { id: 1, school_id: 1, score: 18, version: 1 } }]);
    db.__setPoolForTests(null);
    assert.strictEqual(calls[0][0], 'BEGIN');
    assert.ok(calls.some(c => String(c[0]).startsWith('INSERT INTO "grades"')));
    assert.ok(calls.some(c => c[0] === 'COMMIT'));
    assert.ok(calls.some(c => c[0] === 'RELEASE'));
  });

  await okAsync('OCC در UPDATE به WHERE id AND version تبدیل و conflict به 409 تبدیل می‌شود', async () => {
    const calls = [];
    const client = { query: async (sql, params) => {
      calls.push([sql, params]);
      if(String(sql).startsWith('UPDATE "grades"')) return { rowCount: 0, rows: [] };
      return { rowCount: 1, rows: [] };
    }, release: () => calls.push(['RELEASE']) };
    db.__setPoolForTests({ connect: async () => client, end: async () => {} });
    let err = null;
    try { await db.persistOpsBatch([{ c: 'grades', t: 'upd', id: 7, base_version: 3, data: { id: 7, score: 19, version: 4 } }]); }
    catch(e){ err = e; }
    db.__setPoolForTests(null);
    assert.ok(err);
    assert.strictEqual(err.status, 409);
    const upd = calls.find(c => String(c[0]).startsWith('UPDATE "grades"'));
    assert.match(upd[0], /WHERE id = \$\d+ AND version = \$\d+/);
    assert.deepStrictEqual(upd[1].slice(-2), [7, 3]);
    assert.ok(calls.some(c => c[0] === 'ROLLBACK'));
  });

  console.log('\n────────────────────────────────────────────────────');
  console.log('db-engineering: ' + pass + '/' + pass + ' سبز ✅');
})();
