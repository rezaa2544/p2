#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════
   pilot-rollout-coverage.js — سنجه‌های طرح پایلوت پیش از استقرار ملی:
     PR-SEC   یازده بخش الزامی + پیش‌شرط شروع
     PR-GATE  پیش‌شرط‌های گو (اتصال به بستهٔ انتشار و ردیاب)
     PR-SCOPE دامنه: شهرستان/کاربران/نقش‌ها/مقاطع
     PR-KPI   جدول موفقیت‌سنجی با شش معیار
     PR-FASE  پنج فاز با دروازهٔ ورود/خروج
     PR-TRN   آموزش: نقش‌ها + کی‌پی‌آی سی دقیقه
     PR-SUP   مدل پشتیبانی: کشیک + شدت/اس‌ال‌ای + تریاژ + ارتقا
     PR-FBK   جمع‌آوری بازخورد چهار کاناله
     PR-RBK   چهار محرک بازگشت با آستانه
     PR-REV   بازبینی پساپایلوت با سه تصمیم
     PR-BUD   بودجه و منابع
     PR-COM   برنامهٔ ارتباطی سه‌مخاطبه
     PR-REF   ارجاع‌های فایلِ زنده
   اجرا: node tests/pilot-rollout-coverage.js
   ═══════════════════════════════════════════════════════════════════ */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
let pass = 0, fail = 0; const errors = [];
function chk(name, cond, extra) {
  if (cond) { pass++; console.log('  ✅ ' + name); }
  else { fail++; errors.push(name + (extra ? ' — ' + String(extra).slice(0, 200) : '')); console.log('  ❌ ' + name + (extra ? '  —  ' + String(extra).slice(0, 200) : '')); }
}
function grp(t) { console.log('\n▸ ' + t); }
const rd = (p) => { try { return fs.readFileSync(path.join(ROOT, p), 'utf8'); } catch (e) { return null; } };
const sec = (doc, from, to) => doc.split(from)[1].split(to)[0];

const doc = rd('docs/PILOT_ROLLOUT_PLAN.md');
if (!doc) { console.log('❌ docs/PILOT_ROLLOUT_PLAN.md نیست'); process.exit(1); }

grp('PR-SEC — بخش‌های سند');
[
  ['پیش‌شرط شروع پایلوت', /پیش‌شرط شروع پایلوت/],
  ['خلاصهٔ مدیریتی', /خلاصهٔ مدیریتی/],
  ['دامنهٔ پایلوت', /دامنهٔ پایلوت/],
  ['موفقیت‌سنجی', /موفقیت‌سنجی/],
  ['فازهای استقرار', /فازهای استقرار/],
  ['مواد آموزشی', /مواد آموزشی/],
  ['مدل پشتیبانی', /مدل پشتیبانی/],
  ['جمع‌آوری داده و بازخورد', /جمع‌آوری داده و بازخورد/],
  ['محرک‌های بازگشت', /محرک‌های بازگشت/],
  ['بازبینی پساپایلوت', /بازبینی پساپایلوت/],
  ['بودجه و منابع', /بودجه و منابع/],
  ['برنامهٔ ارتباطی', /برنامهٔ ارتباطی/],
  ['محدودیت‌های صادقانه', /محدودیت‌های صادقانه/]
].forEach(([label, re]) => chk('بخشِ «' + label + '»', re.test(doc)));

grp('PR-GATE — پیش‌شرط‌ها (پایلوت دور زدن گیت نیست)');
const gate = sec(doc, 'پیش‌شرط شروع پایلوت', 'خلاصهٔ مدیریتی');
chk('منوط به نتیجهٔ «گو» در ماتریس §۵', /گو/.test(gate) && /ماتریس §۵/.test(gate));
chk('بستن شش مانع پ0 شرط است', /شش مانع پ0/.test(gate) && /P0_BLOCKER_TRACKER\.md/.test(gate));
chk('چهار امضای ذی‌نفعان', /چهار امضا/.test(gate));
chk('پر بودن نتایج بار پیش از پایلوت', /LOAD_TEST_RESULTS\.md/.test(gate));
chk('رصد زنده شرط پایلوت است', /رصد زنده/.test(gate) || /آلارم/.test(gate));

grp('PR-SCOPE — دامنه');
chk('یک شهرستان با ۳۰–۵۰ مدرسه', /یک شهرستان/.test(doc) && /۳۰ تا ۵۰ مدرسه/.test(doc));
chk('حدود ۱۰هزار دانش‌آموز', /۱۰٬۰۰۰/.test(doc));
chk('حدود ۵۰۰ دبیر و ۷هزار ولی', /۵۰۰/.test(doc) && /۷٬۰۰۰/.test(doc));
['مدیر', 'معاون', 'دبیر', 'ولی', 'دانش‌آموز'].forEach((r) => chk('نقشِ «' + r + '» در دامنه', doc.includes(r)));
['دبستان', 'متوسطهٔ اول', 'متوسطهٔ دوم'].forEach((m) => chk('مقطعِ «' + m + '»', doc.includes(m)));
chk('معیارهای انتخاب شهرستان', /معیارهای انتخاب شهرستان/.test(doc));
chk('قید صادقانه: پایلوت ظرفیت ملی را اثبات نمی‌کند', /پایلوت ظرفیت ملی را اثبات نمی‌کند|ظرفیت را اثبات نمی‌کند/.test(doc));

grp('PR-KPI — موفقیت‌سنجی');
const kpi = sec(doc, 'موفقیت‌سنجی', 'فازهای استقرار');
[
  ['دسترس ≥ ۹۹.۵٪', /۹۹\.۵٪/],
  ['پی۹۵ زیر ۳۰۰ میلی‌ثانیه', /< ?۳۰۰ms|زیر ۳۰۰/],
  ['رضایت ≥ ۸۰٪', /۸۰٪/],
  ['پایبندی دبیر ≥ ۷۰٪', /۷۰٪/],
  ['موفقیت سینک ≥ ۹۵٪', /۹۵٪/],
  ['باگ کمتر از ۵ در هفته', /۵ در هفته/]
].forEach(([label, re]) => chk('معیار «' + label + '»', re.test(kpi)));
chk('روش اندازه‌گیری برای معیارها (پرومتهوس/نظرسنجی/لاگ/ردیاب)', /پرومتهوس/.test(kpi) && /نظرسنجی/.test(kpi) && /لاگ/.test(kpi) && /ردیاب مسئله/.test(kpi));

grp('PR-FASE — فازهای پنج‌گانه');
const fase = sec(doc, 'فازهای استقرار', 'مواد آموزشی');
['فاز ۰', 'فاز ۱', 'فاز ۲', 'فاز ۳', 'فاز ۴'].forEach((p) => chk('«' + p + '» در جدول', fase.includes(p)));
chk('هفته‌بندی مطابق ابلاغ (۱–۲، ۳، ۵، ۷، ۹–۱۲)', /هفتهٔ ۱–۲/.test(fase) && /هفتهٔ ۳/.test(fase) && /هفتهٔ ۵/.test(fase) && /هفتهٔ ۷/.test(fase) && /هفتهٔ ۹–۱۲/.test(fase));
chk('دروازهٔ ورود و خروج هر فاز', /دروازهٔ ورود/.test(fase) && /دروازهٔ خروج/.test(fase));
chk('گسترش فقط با تأیید — جهش پله ممنوع', /جهش پله ممنوع/.test(fase));

grp('PR-TRN — آموزش');
const trn = sec(doc, 'مواد آموزشی', 'مدل پشتیبانی');
chk('راهنمای گام‌به‌گام', /گام‌به‌گام/.test(trn));
chk('ویدئو در صورت امکان', /ویدئو/.test(trn));
chk('کی‌پی‌آی سی دقیقه برای هر نقش', /۳۰ دقیقه/.test(trn));
chk('مسیر پشتیبانی: تیکت + واک‌ترو + خط تماس', /تیکت/.test(trn) && /walkthrough/.test(trn) && /خط تماس/.test(trn));

grp('PR-SUP — مدل پشتیبانی');
const sup = sec(doc, 'مدل پشتیبانی', 'جمع‌آوری داده و بازخورد');
chk('کشیک ۲۴/۷ در هفتهٔ اول', /۲۴\/۷/.test(sup));
chk('چرخش کشیک', /چرخشی|شیفت/.test(sup));
chk('شدت‌ها همان پ0–پ3 سند حادثه (بدون منبع دونگانی)', /INCIDENT_RESPONSE\.md/.test(sup) && /دونگانی نمی‌سازیم/.test(sup));
chk('جدول شدت→زمان پاسخ', /تأیید حضور/.test(sup) && /هدف حل/.test(sup));
chk('فرایند تریاژ', /تریاج|سطح‌بندی/.test(sup));
chk('مسیر ارتقا تا ناظر', /مسیر ارتقا/.test(sup) && /ناظر/.test(sup));

grp('PR-FBK — بازخورد');
const fbk = sec(doc, 'جمع‌آوری داده و بازخورد', 'محرک‌های بازگشت');
chk('دکمهٔ بازخورد درون‌برنامه‌ای (با قید صادقانهٔ نبودن)', /دکمهٔ بازخورد/.test(fbk) && /در محصول نیست/.test(fbk));
chk('نظرسنجی هفتگی پنج سؤالی', /هفتگی/.test(fbk) && /۵ سؤال/.test(fbk));
chk('گروه متمرکز ماهانه', /گروه متمرکز|focus group/.test(fbk) && /ماهانه/.test(fbk));
chk('ضبط نشست فقط با رضایت', /با رضایت/.test(fbk));
chk('حریم دانش‌آموز: رضایت ولی + ماسک داده', /رضایت ولی/.test(fbk) && /ماسک/.test(fbk));

grp('PR-RBK — محرک‌های بازگشت');
const rbk = sec(doc, 'محرک‌های بازگشت', 'بازبینی پساپایلوت');
chk('دسترس < ۹۵٪ در ۲۴ ساعت → توقف فاز', /۹۵٪/.test(rbk) && /توقف فاز/.test(rbk));
chk('فساد داده → بازگشت فوری', /فساد/.test(rbk) && /بازگشت فوری/.test(rbk));
chk('شکایت امنیتی جدی → بررسی فوری + تصمیم', /امنیتی جدی/.test(rbk) && /بررسی فوری/.test(rbk));
chk('رضایت < ۵۰٪ → بازبینی طرح', /۵۰٪/.test(rbk) && /بازبینی طرح/.test(rbk));
chk('بازگشت کامل طبق برنامهٔ بازگشت بستهٔ انتشار', /GO_LIVE_PACKAGE\.md/.test(rbk) && /برنامهٔ بازگشت/.test(rbk));

grp('PR-REV — پساپایلوت');
const rev = sec(doc, 'بازبینی پساپایلوت', 'بودجه و منابع');
chk('چه چیزی کار کرد / نکرد', /آنچه کار کرد/.test(rev) && /آنچه کار نکرد/.test(rev));
chk('سه تصمیم: ادامه/تعدیل/توقف', /ادامه به ملی/.test(rev) && /تعدیل/.test(rev) && /توقف/.test(rev));
chk('اقدام‌های فاز ملی با مالک و مهلت', /اقدام‌های فاز ملی/.test(rev) && /مالک/.test(rev));

grp('PR-BUD — بودجه');
const bud = sec(doc, 'بودجه و منابع', 'برنامهٔ ارتباطی');
chk('تیم فنی کشیک', /تیم فنی/.test(bud));
chk('تیم پشتیبانی ۳–۵ نفر', /۳–۵ نفر/.test(bud));
chk('ردیف آموزش', /آموزش/.test(bud));
chk('ردیف زیرساخت', /زیرساخت/.test(bud));
chk('صداقت مالی: اعداد ریالی نیامده', /اعداد ریالی عمداً/.test(bud));

grp('PR-COM — ارتباطات');
const com = sec(doc, 'برنامهٔ ارتباطی', 'محدودیت‌های صادقانه');
chk('هفتگی به مدیران مدارس', /مدیران مدارس/.test(com) && /هفتگی/.test(com));
chk('ماهانه به وزارت', /وزارت/.test(com) && /ماهانه/.test(com));
chk('صفحهٔ وضعیت عمومی', /صفحهٔ وضعیت/.test(com));
chk('قاعدهٔ اطلاع ۳۰ دقیقه‌ای حادثه', /۳۰ دقیقه/.test(com));

grp('PR-REF — ارجاع‌ها');
const refs = [...new Set((doc.match(/(?:docs|server|infra|tests|tools)\/[A-Za-z0-9_./-]+\.(?:json|md|js|yml|sh|sql)/g) || []))];
chk('سند به فایل‌های ریپو ارجاع می‌دهد', refs.length >= 5, String(refs.length));
const dead = refs.filter((ref) => !fs.existsSync(path.join(ROOT, ref)));
chk('همهٔ ارجاع‌ها به فایلِ موجود می‌رسند', dead.length === 0, dead.join(','));

console.log('\n──────────────────────────────────────────');
console.log('نتیجه: ' + pass + ' موفق / ' + fail + ' ناموفق (از ' + (pass + fail) + ')');
if (fail > 0) { console.log('موارد ناموفق:\n- ' + errors.join('\n- ')); process.exit(1); }
console.log('✅ طرح پایلوت کامل و سازگار با اسناد بالادستی است.');
